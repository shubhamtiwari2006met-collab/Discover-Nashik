type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function getSessionLanguage(): Language {
  if (typeof window === "undefined") return "en";
  try {
    const saved = window.sessionStorage.getItem("discover-nashik-language") as Language | null;
    return saved && (saved === "en" || saved === "hi" || saved === "mr") ? saved : "en";
  } catch (e) {
    return "en";
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    const initialLang = getSessionLanguage();
    setLanguageState(initialLang);
  }, []);

  useEffect(() => {
    if (typeof window === "undefined") return;
    document.documentElement.lang = language;
    document.documentElement.classList.toggle("devanagari", language !== "en");
  }, [language]);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    if (typeof window !== "undefined") {
      try {
        window.sessionStorage.setItem("discover-nashik-language", next);
      } catch (e) {
        // ignore storage errors
      }
    }
  }, []);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (key: string) =>
        (translations[language] && translations[language][key]) ||
        (translations.en && translations.en[key]) ||
        key,
    }),
    [language, setLanguage]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useTranslation() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useTranslation must be used inside I18nProvider");
  return context;
}
